import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const manifest=JSON.parse(read('manifest.json'));
const core=read('index.js');
const theater=read('modules/theater/index.js');
const relay=read('modules/theater/relay.js');
const qa=read('modules/author-qa/index.js');
const qaPrompt=read('modules/creative/author-qa.js');
const hub=read('memory-hub/app.js');
const server=read('server-plugin/vvv-theater-memory-server/index.mjs');
assert.equal(manifest.id,'vvv_story_memory_suite');
assert.equal(manifest.generate_interceptor,'vvvStoryMemoryInterceptor');
assert.equal(manifest.auto_update,true);
for(const token of ['vvvTheaterMemoryInterceptor','VVVUnifiedCore','events','tasks','overlays'])assert.ok(core.includes(token),`core missing ${token}`);
for(const token of ['fixed39-single-world-complete','fixed40-new-chat-turn-guard','fixed41-generation-order-guard','fixed42-network-state-single-source'])assert.ok(theater.includes(token),`theater missing ${token}`);
for(const token of ['storyLedger: []','acquaintanceLedger: []','function s39RecordStoryEvent','function s39NarrativeShoppingOrders','function s39SyncNarrativePhoneRealityImmediate','canonicalCommunicationReason'])assert.ok(theater.includes(token),`single-world/network marker missing ${token}`);
assert.ok(theater.includes("const MODULE = 'vvv_theater_memory'"),'0-32 settings id changed');
assert.ok(relay.includes('vvv_story_relay'),'relay settings id changed');
assert.ok(relay.includes('VVVTheaterMemoryBridge'),'relay lost memory bridge');
assert.ok(relay.includes('completeTruncatedRelayText'),'relay anti-truncation lost');
assert.ok(qaPrompt.includes('【VVV作者场外问答｜本轮暂停角色扮演】'),'author marker changed');
assert.ok(qa.includes('injectAuthorQaPrompt'),'standalone author QA injector missing');
assert.ok(qa.includes("await mod.Generate('regenerate')"),'author answer recovery missing');
assert.ok(hub.includes("const API='/api/plugins/vvv-theater-memory-server'"),'Memory Hub endpoint changed');
assert.ok(server.includes('multi-account mode'),'server multi-account mode missing');
assert.ok(server.includes('initializeAccountStorage'),'server per-account initialization missing');
assert.ok(server.includes('account-required'),'server account isolation guard missing');
assert.ok(theater.includes('/scripts/extensions/third-party/vvv-story-memory-suite/memory-hub/index.html'),'Memory Hub standalone path not patched');
assert.ok(!theater.includes('/scripts/extensions/third-party/vvv-unified-core/memory-hub/index.html'),'legacy Memory Hub path remains');
for(const absent of ['modules/cardvault/index.js','modules/creative/index.js'])assert.ok(!fs.existsSync(path.join(root,absent)),`unwanted module included: ${absent}`);
console.log('PASS standalone integrity: 0-32 + relay + RAG/Memory Hub + author QA preserve fixed42 data/bridge ids, single-world behavior, and multi-account startup.');
